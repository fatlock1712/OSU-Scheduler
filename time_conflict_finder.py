def get_available_classes(all_api_classes, desired_course_codes):
    """Filters for open, requested classes and groups them by course code."""
    grouped_classes = {code: [] for code in desired_course_codes}

    for c in all_api_classes:
        code = c.get("code", "").upper()
        # Only keep it if the user wants it, it's not full ('F'), and not cancelled ('Y')
        if code in desired_course_codes and c.get("stat") != "F" and c.get("isCancelled") != "Y":
            grouped_classes[code].append(c)

    return grouped_classes

def bundle_components(course_classes):
    """
    Dynamically pairs up linked components based on section numbers.
    Includes a fallback for parallel standalone tracks (like Ecampus vs Corvallis).
    """
    component_types = list(set([c.get("schd") for c in course_classes]))

    if len(component_types) <= 1:
        return [[c] for c in course_classes]

    primary = [c for c in course_classes if c.get("schd") == component_types[0]]
    secondary = [c for c in course_classes if c.get("schd") == component_types[1]]

    # --- NEW: The Parallel Track Check ---
    # Check which campuses the primary and secondary components exist on
    campuses_primary = set([c.get("camp") for c in primary])
    campuses_secondary = set([c.get("camp") for c in secondary])

    # If they share NO campuses, they are parallel tracks, not pairs.
    # e.g., Corvallis 'A' vs Ecampus 'L'
    if not campuses_primary.intersection(campuses_secondary):
        return [[c] for c in course_classes] # Treat them ALL as standalone!
    # -------------------------------------

    bundles = []

    # Attempt 1: Strict Linkage (Matching first 2 characters)
    for prim in primary:
        for sec in secondary:
            if prim.get("camp") != sec.get("camp"):
                continue

            p_sec = prim.get("no", "")
            s_sec = sec.get("no", "")

            if p_sec and s_sec and (p_sec[:2] == s_sec[:2]):
                if not check_overlap(prim, sec):
                    bundles.append([prim, sec])

    # Attempt 2: Open Linkage (Fallback for Math Department)
    if not bundles:
        for prim in primary:
            for sec in secondary:
                if prim.get("camp") != sec.get("camp"):
                    continue

                if not check_overlap(prim, sec):
                    bundles.append([prim, sec])

    return bundles

