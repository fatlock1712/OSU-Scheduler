def analyze_valid_schedule(valid_combination):
    total_credits = 0.0
    """Calculates total fees, extracts CRNs, and formats the schedule."""
    flat_schedule = [course for bundle in valid_combination for course in bundle]

    total_fees = 0.0
    instructors = set()
    crns = []  # NEW: List to hold the CRNs

    for course in flat_schedule:
        instructors.add(course.get("instr", "TBA"))

        # NEW: Grab the CRN, default to 'N/A' if missing for some reason
        crns.append(course.get("crn", "N/A"))

        fee_str = course.get("ssrFees", "").strip()
        if fee_str:
            try:
                total_fees += float(fee_str)
            except ValueError:
                pass # Ignore if fee string is unreadable
        credit_str = course.get("hours_html", "0").strip()
        try:
          total_credits += float(credit_str)
        except ValueError:
          pass
    return {
    "schedule": flat_schedule,
    "instructors": list(instructors),
    "total_fees": total_fees,
    "total_credits": total_credits,
    "crns": crns
      }

def export_schedules_to_csv(analyzed_schedules, filename="my_possible_schedules.csv"):
    """Writes the successful schedules to a CSV file."""
    if not analyzed_schedules:
        print("\nNo valid schedules found. Try adjusting your course list.")
        return

    # NEW: Added "Total Credits" as a new column header before Fees
    headers = ["Option", "Courses", "CRNs", "Meeting Times", "Instructors", "Total Credits", "Total Fees ($)"]

    # Tip: 'utf-8-sig' makes sure Excel reads the '$' symbols correctly
    with open(filename, mode='w', newline='', encoding='utf-8-sig') as file:
        writer = csv.writer(file)
        writer.writerow(headers)

        for index, sched in enumerate(analyzed_schedules):
            course_codes = ", ".join([c["code"] for c in sched["schedule"]])
            crns = ", ".join(sched["crns"])
            meeting_times = ", ".join([f"{c['code']} ({c.get('meets', 'TBA')})" for c in sched["schedule"]])
            instructors = ", ".join(sched["instructors"])

            # Format the numbers nicely
            fees = f"{sched.get('total_fees', 0):.2f}"

            # NEW: Extract the credits from the dictionary and format to 1 decimal (e.g., "12.0")
            credits = f"{sched.get('total_credits', 0):.1f}"

            # NEW: Make sure 'credits' is added to this list in the exact same order as the headers!
            writer.writerow([index + 1, course_codes, crns, meeting_times, instructors, credits, fees])

    print(f"\nSuccess! Saved {len(analyzed_schedules)} schedule options to {filename}")

