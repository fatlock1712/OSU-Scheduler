def time_to_minutes(time_str):
    """Converts a time string like '1350' to total minutes since midnight."""
    time_int = int(time_str)
    hours = time_int // 100
    minutes = time_int % 100
    return (hours * 60) + minutes

def dates_overlap(start1_str, end1_str, start2_str, end2_str):
    """Checks if two YYYY-MM-DD date ranges overlap."""
    # If a class is missing dates for some reason, assume they overlap to be safe
    if not all([start1_str, end1_str, start2_str, end2_str]):
        return True

    date_format = "%Y-%m-%d"
    try:
        s1 = datetime.strptime(start1_str, date_format)
        e1 = datetime.strptime(end1_str, date_format)
        s2 = datetime.strptime(start2_str, date_format)
        e2 = datetime.strptime(end2_str, date_format)

        # Standard overlap formula for dates
        return (s1 <= e2) and (s2 <= e1)
    except ValueError:
        # If the API returns weirdly formatted text instead of dates, play it safe
        return True


def check_overlap(class1, class2):
    """Returns True if the two classes have a time and date conflict."""

    # NEW: Check if the calendar dates actually overlap!
    if not dates_overlap(class1.get("start_date", ""), class1.get("end_date", ""),
                         class2.get("start_date", ""), class2.get("end_date", "")):
        return False # They happen in totally different weeks/months!

    # Handle cases where a class might not have meeting times listed
    if not class1.get("meetingTimes") or not class2.get("meetingTimes"):
        return False

    try:
        times1 = json.loads(class1["meetingTimes"])
        times2 = json.loads(class2["meetingTimes"])
    except json.JSONDecodeError:
        return False

    for t1 in times1:
        for t2 in times2:
            if t1["meet_day"] == t2["meet_day"]:
                start1 = time_to_minutes(t1["start_time"])
                end1 = time_to_minutes(t1["end_time"])
                start2 = time_to_minutes(t2["start_time"])
                end2 = time_to_minutes(t2["end_time"])

                # Standard overlap formula for daily times
                if (start1 < end2) and (start2 < end1):
                    return True # Conflict found!

    return False



def schedule_has_conflicts(schedule_tuple):
    """Checks an entire generated schedule for any internal overlaps."""
    # Flatten the schedule (since bundles contain multiple classes)
    flat_schedule = [course for bundle in schedule_tuple for course in bundle]

    # Check every unique pair of classes in the schedule
    for class1, class2 in itertools.combinations(flat_schedule, 2):
        if check_overlap(class1, class2):
            return True
    return False

