def fetch_course_data(course_code, term_code):
    """
    Fetches data using the standard CourseLeaf POST payload structure.
    """
    # 1. Clean the URL (Remove the alias and stat from the link)
    url = "https://classes.oregonstate.edu/api/?page=fose&route=search"

    # Pad with spaces so it completely overwrites previous lines in the terminal
    print(f"Fetching {course_code} for term {term_code}...       ", end="\r")

    headers = {
        "Accept": "application/json",
        "Content-Type": "application/json",
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120.0.0.0 Safari/537.36"
    }

    # 2. Bundle EVERYTHING into the payload (Term + Course Code)
    payload = {
        "other": {
            "srcdb": term_code
        },
        "criteria": [
            {
                "field": "alias",
                "value": course_code  # e.g., "ENGR 103"
            }
        ]
    }

    try:
        # Send the payload via POST
        response = requests.post(url, json=payload, headers=headers)
        response.raise_for_status()
        data = response.json()

        if isinstance(data, dict):
            if "results" in data and isinstance(data["results"], list):
                return data["results"]
            else:
                print(f"\n  -> API returned unexpected data for {course_code}: {data}")
                return []

        elif isinstance(data, list):
            return data
        else:
            return []

    except requests.exceptions.RequestException as e:
        print(f"\n  -> Error connecting to API for {course_code}: {e}")
        return []
    except ValueError:
        print(f"\n  -> Error: API did not return valid JSON for {course_code}.")
        return []
