def fetch_section_details(unique_key, term_code):
    """Hits the 'details' route to grab the missing credit hours."""
    url = "https://classes.oregonstate.edu/api/?page=fose&route=details"

    headers = {
        "Accept": "application/json",
        "Content-Type": "application/json",
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"
    }

    # CourseLeaf requires the word 'key:' in front of the actual key number
    payload = {
        "key": f"key:{unique_key}",
        "srcdb": term_code
    }

    try:
        response = requests.post(url, json=payload, headers=headers)
        if response.status_code == 200:
            return response.json()
    except:
        pass
    return {}

