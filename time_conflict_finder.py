def get_user_term():
    """
    Dynamically generates the OSU term code based on the season and calendar year.
    Formula:
    - Summer/Fall: (Year + 1) + Suffix (00 or 01)
    - Winter/Spring: Year + Suffix (02 or 03)
    """
    print("\n--- Select Term ---")

    # Mapping the seasons to their API suffixes
    term_suffixes = {
        "1": ("SUMMER", "00"),
        "2": ("FALL", "01"),
        "3": ("WINTER", "02"),
        "4": ("SPRING", "03")
    }

    # 1. Get the Season
    print("1 - Summer\n2 - Fall\n3 - Winter\n4 - Spring")
    while True:
        season_choice = input("Select Season (1-4) [Default: 2 (Fall)]: ").strip()
        if season_choice == "":
            season_choice = "2"

        if season_choice in term_suffixes:
            season_name, suffix = term_suffixes[season_choice]
            break
        print("Invalid choice. Please enter 1, 2, 3, or 4.")

    # 2. Get the Year
    from datetime import datetime
    current_year = datetime.now().year

    while True:
        year_input = input(f"Enter Year (e.g., 2026) [Default: {current_year}]: ").strip()
        if year_input == "":
            calendar_year = current_year
            break

        if len(year_input) == 4 and year_input.isdigit():
            calendar_year = int(year_input)
            break
        print("Invalid year. Please enter a 4-digit year.")

    # 3. Apply the "Academic Year" Math
    if season_name in ["SUMMER", "FALL"]:
        # Summer and Fall belong to the *next* academic year
        academic_year = calendar_year + 1
    else:
        # Winter and Spring belong to the *current* academic year
        academic_year = calendar_year

    # 4. Construct the final 6-digit API code
    api_term_code = f"{academic_year}{suffix}"

    print(f" -> Setting search for {season_name.capitalize()} {calendar_year} (API Code: {api_term_code})")

    return api_term_code
